<script>
export default {
  name: 'ContactForm',
  data() {
    return {
      form: {
        nombre: '',
        email: '',
        asunto: '',
        mensaje: ''
      },
      enviando: false,
      mensajeExito: '',
      mensajeError: ''
    }
  },
  methods: {
    async enviarConsulta() {
      this.enviando = true
      this.mensajeExito = ''
      this.mensajeError = ''

      try {
        const response = await fetch('https://petruworkout-production.up.railway.app/api/consultas/enviar', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(this.form)
        })

        const data = await response.json()

        if (response.ok && data.success) {
          this.mensajeExito = 'Mensaje enviado correctamente. Te responderé pronto.'
          this.limpiarFormulario()
        } else {
          this.mensajeError = data.error || 'Error al enviar el mensaje'
        }
      } catch (error) {
        this.mensajeError = 'Error de conexión. Intenta de nuevo.'
      } finally {
        this.enviando = false
      }
    },

    limpiarFormulario() {
      this.form = {
        nombre: '',
        email: '',
        asunto: '',
        mensaje: ''
      }
    }
  }
}
</script>

